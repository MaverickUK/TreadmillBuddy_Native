#!/usr/bin/env python3
"""Generate test/native/plan_fixtures.h from the CircuitPython plan.py.

    python3 test/gen_plan_fixtures.py ../TreadmillBuddy > test/native/plan_fixtures.h

Runs the original plan.py (with its own settings.py defaults) and records
what it does, so the host tests can check the C++ port against it:

* BOOST: random-walk base plans, and the plan apply_boost() makes from each
  for a range of presses, plus boost_limits().
* ZIGZAG: generate_plan() with RANDOM_PLAN = False, for every session length.
* OPS: the planning screen as code.py drives it: a starting base, then a
  stream of X/Y presses on INTENSITY (+1/-1) and TIME (+2/-2), and the state
  that results; then fresh_plan(). With RANDOM_PLAN = False the whole thing
  is deterministic. With RANDOM_PLAN = True only shrinking TIME is used (a
  longer walk would roll new random segments) and fresh_plan() is skipped.

Speeds are written in tenths of a km/h. Standard library only.
"""
import random
import sys

sys.dont_write_bytecode = True  # leave no __pycache__ in the CircuitPython repo
sys.path.insert(0, sys.argv[1])
import settings  # noqa: E402
import plan  # noqa: E402


def tenths(v):
    return int(round(v * 10))


def plan_tenths(p):
    return [tenths(s) for s in p]


def generate(duration, random_plan):
    settings.RANDOM_PLAN = random_plan
    cfg = plan.SessionConfig()
    cfg.duration_min = duration
    return cfg, plan.generate_plan(cfg)


def boost_cases(rng):
    data = []
    count = 0
    for duration in (5, 10, 15, 20, 25, 40, 60, 120):
        for _ in range(4):
            random.seed(rng.randrange(1 << 30))
            _, base = generate(duration, True)
            low, high = plan.boost_limits(base)
            smin, smax = low - 2, high + 2
            data += [len(base)] + plan_tenths(base) + [low, high, smin, smax]
            for steps in range(smin, smax + 1):
                data += plan_tenths(plan.apply_boost(base, steps))
            count += 1
    return [count] + data


def zigzag_cases():
    data = []
    count = 0
    for duration in range(settings.MIN_SESSION_DURATION_MIN, settings.MAX_SESSION_DURATION_MIN + 1,
                          settings.TIME_STEP_MIN):
        _, p = generate(duration, False)
        data += [duration, len(p)] + plan_tenths(p)
        count += 1
    return [count] + data


def op_cases(rng):
    data = []
    count = 0
    for random_plan in (False, True):
        for _ in range(40):
            random.seed(rng.randrange(1 << 30))
            duration = rng.choice(range(settings.MIN_SESSION_DURATION_MIN,
                                        settings.MAX_SESSION_DURATION_MIN + 1, settings.TIME_STEP_MIN))
            cfg, base = generate(duration, random_plan)
            shown = plan.apply_boost(base, cfg.boost)
            start_base = list(base)
            choices = (1, -1, 2, -2) if not random_plan else (1, -1, -2)
            ops = [rng.choice(choices) for _ in range(rng.randrange(1, 30))]
            for op in ops:  # as code.py does on the planning screen
                steps = 1 if op > 0 else -1
                if abs(op) == 2:
                    if cfg.adjust_time(steps):
                        base, shown = plan.resize_plan(cfg, base, shown)
                elif cfg.adjust_boost(steps, base):
                    shown = plan.apply_boost(base, cfg.boost)
            data += [1 if random_plan else 0, duration, len(start_base)] + plan_tenths(start_base)
            data += [len(ops)] + ops
            data += [cfg.duration_min, len(base)] + plan_tenths(base) + plan_tenths(shown)
            data += [cfg.boost, cfg.boost_carry, tenths(cfg.boost_kph)]
            data += [int(round(plan.planned_distance_km(shown) * 100))]
            if not random_plan:
                base, shown = plan.fresh_plan(cfg)
                data += [cfg.boost, cfg.boost_carry, len(shown)] + plan_tenths(shown)
            count += 1
    return [count] + data


def emit(name, values):
    print("constexpr int %s[] = {" % name)
    for i in range(0, len(values), 24):
        print("    " + ", ".join(str(v) for v in values[i:i + 24]) + ",")
    print("};")
    print()


def main():
    rng = random.Random(20261021)
    print("// Generated by test/gen_plan_fixtures.py from the CircuitPython plan.py: do not edit.")
    print("// Speeds are tenths of a km/h; see the script for the layout of each array.")
    print("#pragma once")
    print()
    print("namespace fixtures {")
    print()
    print("// plan.py's settings.py defaults when these were made")
    print("constexpr int MIN_TENTHS = %d, MAX_TENTHS = %d, STEP_TENTHS = %d, START_TENTHS = %d;" % (
        tenths(settings.MIN_SPEED_KPH), tenths(settings.MAX_SPEED_KPH), tenths(settings.SPEED_STEP_KPH),
        tenths(settings.START_SPEED_KPH)))
    print("constexpr int INTERVAL_S = %d, DEFAULT_MIN = %d, TIME_STEP_MIN = %d, MIN_SESSION_MIN = %d, "
          "MAX_SESSION_MIN = %d;" % (
              int(settings.SPEED_CHANGE_INTERVAL_MIN * 60), settings.SESSION_DURATION_MIN, settings.TIME_STEP_MIN,
              settings.MIN_SESSION_DURATION_MIN, settings.MAX_SESSION_DURATION_MIN))
    print()
    emit("BOOST", boost_cases(rng))
    emit("ZIGZAG", zigzag_cases())
    emit("OPS", op_cases(rng))
    print("} // namespace fixtures")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Pre-render a TrueType font into a C++ header for the firmware (see src/font.h).

    python3 scripts/make_font.py fonts/Poppins-Bold.ttf 56 POPPINS_BOLD_56 > src/fonts/poppins_bold_56.h

Covers printable ASCII (32-126). Each glyph is stored as 4-bit coverage,
anti-aliased by FreeType (via Pillow). No kerning: Pillow can only read
Poppins' kerning with libraqm, and the text here doesn't need it.

Needs Pillow (pip install pillow); the generated headers are committed, so
building the firmware doesn't.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126


def main():
    ttf, size, name = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    cap_top = font.getbbox("H")[1]

    bitmap = []
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        left, top, right, bottom = font.getbbox(ch)  # relative to the top-left at the ascender
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            px = img.load()
            for y in range(h):
                row = [(px[x, y] * 15 + 127) // 255 for x in range(w)]
                if len(row) % 2:
                    row.append(0)
                bitmap += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]
        glyphs.append((offset, w, h, left, top - ascent, advance, ch))

    src = os.path.basename(ttf)
    print("// Generated by scripts/make_font.py from %s at %d px: do not edit." % (src, size))
    print("// The font is under the SIL Open Font License 1.1 (fonts/OFL.txt).")
    print("#pragma once")
    print()
    print('#include "../font.h"')
    print()
    print("namespace fonts {")
    print()
    print("constexpr uint8_t %s_BITMAP[] = {" % name)
    for i in range(0, len(bitmap), 24):
        print("    " + ", ".join("0x%02X" % b for b in bitmap[i:i + 24]) + ",")
    print("};")
    print()
    print("constexpr Glyph %s_GLYPHS[] = {" % name)
    for offset, w, h, x_off, y_off, advance, ch in glyphs:
        label = {"\\": "backslash", " ": "space"}.get(ch, ch)
        print("    {%d, %d, %d, %d, %d, %d},  // %s" % (offset, w, h, x_off, y_off, advance, label))
    print("};")
    print()
    print("constexpr Font %s{%s_BITMAP, %s_GLYPHS, %d, %d, %d, %d};" % (
        name, name, name, FIRST, LAST, ascent - cap_top, ascent + descent))
    print()
    print("} // namespace fonts")


if __name__ == "__main__":
    main()
